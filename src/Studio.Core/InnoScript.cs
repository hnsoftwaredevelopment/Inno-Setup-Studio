using System.Text;

namespace Studio.Core;

/// <summary>Generates a native installer script with the two current wizard pages.</summary>
public static class InnoScript
{
    public static string Generate(StudioProject project, string? projectDirectory)
    {
        ProjectFile.Validate(project);
        var languages = LanguageScript.Create(project, projectDirectory);
        var fileLines=new List<string>();
        foreach(var rule in FileCollections.Rules(project))
        {
            var source=FileCollections.ResolvePattern(rule,projectDirectory);
            _=FileCollections.Preview(rule,projectDirectory);
            var line="Source: "+Parameter(source)+"; DestDir: "+Parameter(FileCollections.Destination(rule.Destination));
            if(rule.Excludes.Count>0) line+="; Excludes: "+Parameter(string.Join(",",rule.Excludes));
            if(rule.RecurseSubdirectories) line+="; Flags: recursesubdirs";
            fileLines.Add(line);
        }
        var directory = project.Pages.Single(p => p.Kind == PageKind.Destination).Destination!.DefaultDirectory;
        foreach (var value in new[] { project.Name, project.AppId, project.AppVersion, directory })
            if (value.Contains("{#", StringComparison.Ordinal)) throw Error("ExportPreprocessorUnsupported");

        // Setup directives only strip surrounding quotes; Files parameters unescape doubled quotes.
        var lines = new List<string>
        {
            "; Generated by Inno Setup Studio. Target compiler: Inno Setup 7.1.",
            "; Application details, local file rules and wizard text for all enabled project languages.",
            "[Setup]",
            "AppId=" + SetupValue(Literal(project.AppId)),
            "AppName=" + SetupValue(Literal(project.Name)),
            "AppVersion=" + SetupValue(Literal(project.AppVersion)),
            "DefaultDirName=" + SetupValue(directory),
            "DisableWelcomePage=no",
            "DisableDirPage=no",
            "OutputDir=output",
            "OutputBaseFilename=" + SetupValue(project.OutputBaseFileName),
            "",
            "[Languages]"
        };
        var settings = project.PageSettings;
        string PageValue(string value)
        {
            var expanded = System.Text.RegularExpressions.Regex.Replace(value, @"\{AppName\}|\{AppVersion\}",
                match => Literal(match.Value == "{AppName}" ? project.Name : project.AppVersion));
            if (expanded.Contains("{#", StringComparison.Ordinal)) throw Error("ExportPreprocessorUnsupported");
            return SetupValue(expanded);
        }
        var pageLines = new List<string>();
        if (settings.UserInfoEnabled) pageLines.AddRange([
            "UserInfoPage=yes", "DefaultUserInfoName=" + PageValue(settings.DefaultName),
            "DefaultUserInfoOrg=" + PageValue(settings.DefaultOrganization),
            "UsePreviousUserInfo=" + (settings.UsePreviousUserInfo ? "yes" : "no")]);
        if (settings.GroupMode != ProgramGroupPageMode.Auto)
            pageLines.Add("DisableProgramGroupPage=" + (settings.GroupMode == ProgramGroupPageMode.Show ? "no" : "yes"));
        if (settings.DefaultGroup.Length > 0)
        {
            if (WizardTexts.Expand(settings.DefaultGroup, project).IndexOfAny(['"', ':', '*', '?', '<', '>', '|', '/']) >= 0)
                throw Error("GroupNameInvalid");
            pageLines.Add("DefaultGroupName=" + PageValue(settings.DefaultGroup));
        }
        if (settings.AllowNoIcons) pageLines.Add("AllowNoIcons=yes");
        if (!settings.UsePreviousGroup) pageLines.Add("UsePreviousGroup=no");
        lines.InsertRange(lines.IndexOf("[Languages]") - 1, pageLines);
        var documentLines = project.Documents.Where(p => WizardDocuments.IsActive(p.Value))
            .Select(p => p.Key + "=" + SetupValue(WizardDocuments.Resolve(p.Value.Source, projectDirectory))).ToArray();
        lines.InsertRange(lines.IndexOf("[Languages]") - 1, documentLines);
        foreach (var language in languages)
        {
            var line = "Name: " + Parameter(language.Name) + "; MessagesFile: " + Parameter(language.MessagesFile);
            foreach (var (kind, document) in project.Documents)
                if (WizardDocuments.IsActive(document) && document.Translations.TryGetValue(language.Language.Id, out var variant)
                    && !string.IsNullOrWhiteSpace(variant)) line += "; " + kind + ": " + Parameter(WizardDocuments.Resolve(variant, projectDirectory));
            lines.Add(line);
        }
        lines.AddRange(["","[Files]"]);
        lines.AddRange(fileLines); lines.Add("");
        return string.Join("\r\n", lines) + WizardScript.Generate(project, languages);
    }

    public static string ResolveSource(string source, string? projectDirectory)
    {
        if (string.IsNullOrWhiteSpace(source) || source.Any(char.IsControl)
            || source.IndexOfAny(['*', '?', '"', '<', '>', '|']) >= 0)
            throw Error("ExportSourceInvalid");
        if (Path.IsPathRooted(source) && !Path.IsPathFullyQualified(source)) throw Error("ExportSourceInvalid");
        if (!Path.IsPathFullyQualified(source) && string.IsNullOrWhiteSpace(projectDirectory))
            throw Error("ExportSourceNeedsProject");
        var resolved = Path.IsPathFullyQualified(source) ? Path.GetFullPath(source)
            : Path.GetFullPath(source, projectDirectory!);
        if (!File.Exists(resolved)) throw Error("ExportSourceMissing");
        return resolved;
    }

    public static async Task<byte[]> ReadExportFingerprintAsync(string path)
    {
        await using var stream = File.OpenRead(path);
        return await System.Security.Cryptography.SHA256.HashDataAsync(stream);
    }

    public static async Task ExportAsync(string path, StudioProject project, string? projectDirectory, byte[]? confirmedExistingHash = null)
    {
        if (!string.Equals(Path.GetExtension(path), ".iss", StringComparison.OrdinalIgnoreCase))
            throw Error("ExportExtensionInvalid");
        var script = Generate(project, projectDirectory);
        var fullPath = Path.GetFullPath(path);
        if (FileCollections.Rules(project).SelectMany(rule=>FileCollections.Preview(rule,projectDirectory))
            .Any(file=>string.Equals(fullPath,file.Source,StringComparison.OrdinalIgnoreCase)))
            throw Error("ExportCannotReplaceSource");
        if (File.Exists(fullPath))
        {
            if (await File.ReadAllTextAsync(fullPath) == script) return;
            if (confirmedExistingHash is null) throw Error("ExportExistingProtected");
        }
        async Task VerifyConfirmation()
        {
            if (confirmedExistingHash is not null && (!File.Exists(fullPath)
                || !(await ReadExportFingerprintAsync(fullPath)).SequenceEqual(confirmedExistingHash)))
                throw Error("ExportChangedSinceConfirmation");
        }
        await VerifyConfirmation();
        var temporaryPath = fullPath + $".{Guid.NewGuid():N}.tmp";
        try
        {
            await File.WriteAllTextAsync(temporaryPath, script, new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));
            await VerifyConfirmation();
            // Without confirmation, a file appearing on this path is still preserved.
            File.Move(temporaryPath, fullPath, overwrite: confirmedExistingHash is not null);
        }
        finally { if (File.Exists(temporaryPath)) File.Delete(temporaryPath); }
    }

    private static string Literal(string value) => value.Replace("{", "{{", StringComparison.Ordinal);
    private static string SetupValue(string value) => "\"" + value + "\"";
    private static string Parameter(string value) => "\"" + value.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
    internal static InvalidDataException Error(string key)
    {
        var error = new InvalidDataException(new StudioLocalizer()[key]);
        error.Data["Studio.ResourceKey"] = key;
        return error;
    }
}
